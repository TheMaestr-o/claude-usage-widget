const LANGUAGES = [
    { code: 'en', name: 'English' },
    { code: 'ru', name: 'Русский' },
    { code: 'uk', name: 'Українська' },
    { code: 'de', name: 'Deutsch' },
];

const LOCALES = { en: 'en-US', ru: 'ru-RU', uk: 'uk-UA', de: 'de-DE' };

let currentLang = 'en';

function t(key, vars) {
    const text = (I18N[currentLang] && I18N[currentLang][key]) ?? I18N.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? '')) : text;
}

function currentLocale() {
    return LOCALES[currentLang] || 'en-US';
}

// Fills every element that declares its text by key: text, tooltip (+ aria-label), placeholder
function applyStaticTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
        const text = t(el.dataset.i18nTitle);
        el.title = text;
        el.setAttribute('aria-label', text);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    // A hint only: the element keeps its own visible text as its accessible name
    root.querySelectorAll('[data-i18n-tip]').forEach((el) => {
        el.title = t(el.dataset.i18nTip);
    });
}

function setLanguage(lang) {
    currentLang = I18N[lang] ? lang : 'en';
    document.documentElement.lang = currentLang;
    document.title = t('app.title');
    applyStaticTranslations();
}
